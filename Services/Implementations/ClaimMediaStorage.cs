using PopPop.Data.Entities.Enums;
using PopPop.Models;
using PopPop.Services.Interfaces;

namespace PopPop.Services.Implementations;

public sealed class ClaimMediaStorage : IClaimMediaStorage
{
    private static readonly Dictionary<string, (ClaimMediaKind Kind, string ContentType)> Formats = new(StringComparer.OrdinalIgnoreCase)
    {
        [".mp4"] = (ClaimMediaKind.Video, "video/mp4"),
        [".mov"] = (ClaimMediaKind.Video, "video/quicktime"),
        [".webm"] = (ClaimMediaKind.Video, "video/webm"),
        [".jpg"] = (ClaimMediaKind.Image, "image/jpeg"),
        [".jpeg"] = (ClaimMediaKind.Image, "image/jpeg"),
        [".png"] = (ClaimMediaKind.Image, "image/png"),
        [".webp"] = (ClaimMediaKind.Image, "image/webp")
    };

    private readonly string _root;
    private readonly ILogger<ClaimMediaStorage> _logger;

    public ClaimMediaStorage(IWebHostEnvironment environment, ILogger<ClaimMediaStorage> logger)
    {
        _root = Path.Combine(environment.ContentRootPath, "App_Data", "claims");
        _logger = logger;
    }

    public ClaimMediaLimits Limits { get; } = new();

    public static string ContentTypeFor(string fileName) =>
        Formats.TryGetValue(Path.GetExtension(fileName), out var format) ? format.ContentType : "application/octet-stream";

    public async Task<(ClaimMediaKind? Kind, string? Error)> ValidateAsync(IFormFile file, CancellationToken cancellationToken = default)
    {
        if (file.Length == 0)
        {
            return (null, $"Tệp {file.FileName} đang trống.");
        }

        if (!Formats.TryGetValue(Path.GetExtension(file.FileName), out var format))
        {
            return (null, $"Tệp {file.FileName} không đúng định dạng (video: MP4, MOV, WEBM; ảnh: JPG, PNG, WEBP).");
        }

        var maxBytes = format.Kind == ClaimMediaKind.Video ? Limits.MaxVideoBytes : Limits.MaxImageBytes;
        if (file.Length > maxBytes)
        {
            return (null, $"Tệp {file.FileName} vượt quá {maxBytes / 1024 / 1024} MB.");
        }

        var header = new byte[12];
        await using var stream = file.OpenReadStream();
        var read = await stream.ReadAtLeastAsync(header, header.Length, throwOnEndOfStream: false, cancellationToken);
        return HasValidSignature(Path.GetExtension(file.FileName).ToLowerInvariant(), header, read)
            ? (format.Kind, null)
            : (null, $"Nội dung tệp {file.FileName} không phải là video/ảnh hợp lệ.");
    }

    public async Task<string> SaveAsync(int claimId, IFormFile file, CancellationToken cancellationToken = default)
    {
        var folder = Path.Combine(_root, claimId.ToString(System.Globalization.CultureInfo.InvariantCulture));
        Directory.CreateDirectory(folder);
        var storedName = $"{Guid.NewGuid():N}{Path.GetExtension(file.FileName).ToLowerInvariant()}";
        await using var output = new FileStream(Path.Combine(folder, storedName), FileMode.CreateNew);
        await file.CopyToAsync(output, cancellationToken);
        return storedName;
    }

    public string? GetPath(int claimId, string storedFileName)
    {
        // Stored names are generated by us; GetFileName also defeats any path traversal attempt.
        var path = Path.Combine(_root, claimId.ToString(System.Globalization.CultureInfo.InvariantCulture), Path.GetFileName(storedFileName));
        return File.Exists(path) ? path : null;
    }

    public void Delete(int claimId, string storedFileName)
    {
        var path = GetPath(claimId, storedFileName);
        if (path is null)
        {
            return;
        }

        try
        {
            File.Delete(path);
        }
        catch (IOException exception)
        {
            _logger.LogWarning(exception, "Could not delete claim media {Path}", path);
        }
    }

    private static bool HasValidSignature(string extension, byte[] header, int read)
    {
        bool StartsWith(params byte[] signature) => read >= signature.Length && header.AsSpan(0, signature.Length).SequenceEqual(signature);

        return extension switch
        {
            // ISO base media (MP4/MOV): bytes 4-7 are "ftyp"; older QuickTime files may start with "moov"/"wide"/"mdat".
            ".mp4" or ".mov" => read >= 8 && (header.AsSpan(4, 4).SequenceEqual("ftyp"u8)
                || header.AsSpan(4, 4).SequenceEqual("moov"u8)
                || header.AsSpan(4, 4).SequenceEqual("wide"u8)
                || header.AsSpan(4, 4).SequenceEqual("mdat"u8)),
            ".webm" => StartsWith(0x1A, 0x45, 0xDF, 0xA3),
            ".jpg" or ".jpeg" => StartsWith(0xFF, 0xD8, 0xFF),
            ".png" => StartsWith(0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A),
            ".webp" => read >= 12 && StartsWith(0x52, 0x49, 0x46, 0x46) && header.AsSpan(8, 4).SequenceEqual("WEBP"u8),
            _ => false
        };
    }
}
